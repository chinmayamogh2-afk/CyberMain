import { useState } from 'react';
import { useFindings } from '@/lib/useSecurity';
import { Panel, SeverityBadge, Button, Empty, CodeBlock } from '@/components/ui';
import type { Finding } from '@/lib/types';

/** Vulnerability register + detail (spec §18, §19). */
export function Vulnerabilities() {
  const { findings, loading, reloadFindings } = useFindings();
  const [selected, setSelected] = useState<Finding | null>(null);

  const active = findings.filter((f) => f.status === 'open');
  const resolved = findings.filter((f) => f.status !== 'open');

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-xl font-bold text-white">Vulnerabilities</h1>
        <p className="text-sm text-slate-400">Findings generated by scans and simulations, each with a risk rationale, evidence and a remediation path.</p>
      </div>

      <div className="grid gap-6 lg:grid-cols-[1fr_1.3fr]">
        <div className="space-y-4">
          <Panel title={`Active (${active.length})`} actions={<Button variant="subtle" size="sm" onClick={() => void reloadFindings()}>Refresh</Button>}>
            {loading ? <Empty>Loading…</Empty> : active.length === 0 ? <Empty>No active findings.</Empty> : (
              <div className="space-y-2">
                {active.map((f) => <FindingRow key={f.id} f={f} active={selected?.id === f.id} onClick={() => setSelected(f)} />)}
              </div>
            )}
          </Panel>
          {resolved.length > 0 && (
            <Panel title={`Resolved (${resolved.length})`}>
              <div className="space-y-2">
                {resolved.map((f) => <FindingRow key={f.id} f={f} active={selected?.id === f.id} onClick={() => setSelected(f)} />)}
              </div>
            </Panel>
          )}
        </div>

        <div>
          {selected ? <FindingDetail finding={selected} /> : <Empty>Select a finding to see its full detail.</Empty>}
        </div>
      </div>
    </div>
  );
}

function FindingRow({ f, active, onClick }: { f: Finding; active: boolean; onClick: () => void }) {
  return (
    <button onClick={onClick} className={`flex w-full items-center justify-between rounded-lg px-3 py-2.5 text-left transition ${active ? 'bg-accent/10 ring-1 ring-accent/30' : 'glass-soft hover:bg-white/5'}`}>
      <div className="min-w-0">
        <div className="flex items-center gap-2"><SeverityBadge severity={f.severity} /><span className="truncate text-sm font-medium text-slate-200">{f.title}</span></div>
        <div className="mt-0.5 truncate text-[11px] text-slate-500">{f.endpoint}{f.parameter ? ` · ${f.parameter}` : ''}</div>
      </div>
      <div className="ml-2 text-right">
        <div className="text-xs font-semibold text-slate-300">{f.riskScore}</div>
        <div className={`text-[10px] ${f.status === 'verified' ? 'text-sev-ok' : f.status === 'open' ? 'text-sev-high' : 'text-slate-500'}`}>{f.status}</div>
      </div>
    </button>
  );
}

function FindingDetail({ finding }: { finding: Finding }) {
  const [showWhy, setShowWhy] = useState(true);
  const factors = Object.entries(finding.riskFactors);
  return (
    <Panel title={finding.title} subtitle={`${finding.owaspCategory} · ${finding.cwe ?? ''}`}
      actions={<SeverityBadge severity={finding.severity} />}>
      <div className="space-y-4 text-sm">
        <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
          <Meta label="Risk" value={`${finding.riskScore}/10`} />
          <Meta label="Confidence" value={finding.confidence} />
          <Meta label="Status" value={finding.status} />
          <Meta label="Endpoint" value={finding.endpoint ?? '—'} />
        </div>

        <Section title="Description" body={finding.description} />
        <Section title="Root cause" body={finding.rootCause} />
        <Section title="Attack scenario" body={finding.attackScenario} />
        <Section title="Potential impact" body={finding.impact} />

        <div className="rounded-lg glass-soft p-3">
          <div className="mb-2 text-[11px] uppercase tracking-wider text-slate-500">Risk rationale (why this severity)</div>
          <div className="space-y-1.5">
            {factors.map(([k, v]) => (
              <div key={k} className="flex items-center gap-2">
                <span className="w-44 shrink-0 text-xs capitalize text-slate-400">{k.replace(/([A-Z])/g, ' $1')}</span>
                <div className="h-1.5 flex-1 overflow-hidden rounded-full bg-white/5">
                  <div className="h-full rounded-full bg-accent" style={{ width: `${(v as number) * 100}%` }} />
                </div>
                <span className="w-10 text-right text-xs tabular-nums text-slate-400">{((v as number) * 100).toFixed(0)}%</span>
              </div>
            ))}
          </div>
        </div>

        <div className="flex gap-2">
          <Button variant={showWhy ? 'primary' : 'ghost'} size="sm" onClick={() => setShowWhy(true)}>Show me why this is vulnerable</Button>
          <Button variant={!showWhy ? 'primary' : 'ghost'} size="sm" onClick={() => setShowWhy(false)}>Show me how to fix it</Button>
        </div>
        {showWhy
          ? <div><div className="mb-1 text-[11px] uppercase tracking-wider text-sev-critical">Vulnerable implementation</div><CodeBlock language="code" code={finding.vulnerableExample} /></div>
          : <div className="space-y-3"><div><div className="mb-1 text-[11px] uppercase tracking-wider text-sev-ok">Secure implementation</div><CodeBlock language="code" code={finding.secureExample} /></div><Section title="Verification" body={finding.verification} /></div>}

        <div>
          <div className="mb-1 text-[11px] uppercase tracking-wider text-slate-500">Evidence</div>
          <CodeBlock language="json" code={JSON.stringify(finding.evidence, null, 2)} />
        </div>
      </div>
    </Panel>
  );
}

function Meta({ label, value }: { label: string; value: string }) {
  return <div className="rounded-lg glass-soft px-3 py-2"><div className="text-[10px] uppercase tracking-wider text-slate-500">{label}</div><div className="mt-0.5 truncate text-sm font-medium capitalize text-slate-200">{value}</div></div>;
}
function Section({ title, body }: { title: string; body: string }) {
  return <div><div className="text-[11px] uppercase tracking-wider text-slate-500">{title}</div><p className="mt-1 leading-relaxed text-slate-300">{body}</p></div>;
}
